// Bundle Estedad for offline use and generate styles/src/fonts.css.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "node_modules/@fontsource/estedad";
const OUT = "fonts/estedad";
const SUBSETS = ["arabic", "latin"];
const WEIGHTS = [400, 500, 600, 700, 800, 900];

const ranges = JSON.parse(readFileSync(join(SRC, "unicode.json"), "utf8"));
mkdirSync(OUT, { recursive: true });
copyFileSync(join(SRC, "LICENSE"), join(OUT, "OFL.txt"));

let css = `/* Generated by scripts/build-fonts.mjs: do not edit. Estedad © The Estedad Project Authors, SIL OFL 1.1 (fonts/estedad/OFL.txt). */\n`;
for (const subset of SUBSETS) {
  for (const weight of WEIGHTS) {
    const file = `estedad-${subset}-${weight}-normal.woff2`;
    copyFileSync(join(SRC, "files", file), join(OUT, file));
    css += `@font-face{font-family:"Estedad";font-style:normal;font-display:swap;font-weight:${weight};src:url("../fonts/estedad/${file}") format("woff2");unicode-range:${ranges[subset]};}\n`;
  }
}

writeFileSync("styles/src/fonts.css", css);
console.log(`Estedad: ${SUBSETS.length * WEIGHTS.length} files → ${OUT}`);
